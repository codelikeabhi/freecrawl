// fork: AI formats on a local model (PLAN.md Phase 4). Every AI call goes to
// MODEL_NAME on Ollama (lib/generic-ai.ts), including calls upstream hardcodes
// to OpenAI, Gemini or Fireworks. Sequential: one local model serves them all.
import request from "supertest";
import { describeIf, HAS_AI, scrapeTimeout, TEST_API_URL } from "../lib";
import { idmux, Identity, scrape, scrapeRaw } from "./lib";
import { config } from "../../../config";

const LOCAL_MODEL = !!config.OLLAMA_BASE_URL && !!config.MODEL_NAME;
const PRODUCT =
  "https://books.toscrape.com/catalogue/a-light-in-the-attic_1000/index.html";
const LONG_PAGE = "https://en.wikipedia.org/wiki/PostgreSQL";
const AI_TIMEOUT = scrapeTimeout * 3; // local inference is slower than a scrape

let identity: Identity;

beforeAll(async () => {
  identity = await idmux({
    name: "fork-ai",
    concurrency: 10,
    credits: 1000000,
  });
}, 10000);

describeIf(HAS_AI && LOCAL_MODEL)("Fork: AI formats on the local model", () => {
  it(
    "extracts JSON with a schema",
    async () => {
      const doc = await scrape(
        {
          url: PRODUCT,
          formats: [
            {
              type: "json",
              schema: {
                type: "object",
                properties: {
                  title: { type: "string" },
                  price: { type: "string" },
                },
                required: ["title", "price"],
              },
            },
          ],
          timeout: AI_TIMEOUT,
        },
        identity,
      );
      expect((doc.json as any)?.title).toMatch(/light in the attic/i);
      expect((doc.json as any)?.price).toMatch(/51\.77/);
    },
    AI_TIMEOUT + 10000,
  );

  it(
    "extracts JSON from a prompt alone (schema generated by the model)",
    async () => {
      const doc = await scrape(
        {
          url: PRODUCT,
          formats: [
            { type: "json", prompt: "Extract the book title and its price." },
          ],
          timeout: AI_TIMEOUT,
        },
        identity,
      );
      expect(JSON.stringify(doc.json ?? {})).toMatch(/light in the attic/i);
    },
    AI_TIMEOUT + 10000,
  );

  it(
    "writes a summary",
    async () => {
      const doc = await scrape(
        {
          url: "https://example.com",
          formats: ["summary"],
          timeout: AI_TIMEOUT,
        },
        identity,
      );
      expect(doc.summary?.length ?? 0).toBeGreaterThan(20);
    },
    AI_TIMEOUT + 10000,
  );

  it(
    "answers a question about the page",
    async () => {
      const doc = await scrape(
        {
          url: PRODUCT,
          formats: [
            { type: "question", question: "How much does this book cost?" },
          ],
          timeout: AI_TIMEOUT,
        },
        identity,
      );
      expect(doc.answer).toMatch(/51\.77/);
    },
    AI_TIMEOUT + 10000,
  );

  it(
    "returns highlights (upstream uses a private fine-tune here)",
    async () => {
      const doc = await scrape(
        {
          url: PRODUCT,
          formats: [{ type: "highlights", query: "price and availability" }],
          timeout: AI_TIMEOUT,
        },
        identity,
      );
      expect(doc.highlights?.length ?? 0).toBeGreaterThan(0);
    },
    AI_TIMEOUT + 10000,
  );

  it(
    "turns a crawl prompt into crawl options",
    async () => {
      const res = await request(TEST_API_URL)
        .post("/v2/crawl/params-preview")
        .set("Authorization", `Bearer ${identity.apiKey}`)
        .set("Content-Type", "application/json")
        .send({
          url: "https://books.toscrape.com/",
          prompt: "Only crawl the poetry category, at most 10 pages",
        });
      expect(res.statusCode).toBe(200);
      expect(res.body.success).toBe(true);
      expect(JSON.stringify(res.body.data ?? {})).toMatch(/poetry/i);
    },
    AI_TIMEOUT + 10000,
  );

  // Failure path: a page longer than the model's window must be trimmed with a
  // warning, not sent whole (Ollama would silently cut the prompt, instructions included).
  it(
    "trims a page longer than the context window and says so",
    async () => {
      const raw = await scrapeRaw(
        {
          url: LONG_PAGE,
          formats: [
            {
              type: "json",
              schema: {
                type: "object",
                properties: { name: { type: "string" } },
                required: ["name"],
              },
            },
          ],
          timeout: AI_TIMEOUT,
        },
        identity,
      );
      expect(raw.statusCode).toBe(200);
      expect(raw.body.data.json?.name).toMatch(/postgres/i);
      expect(raw.body.data.warning ?? "").toMatch(/trimmed/i);
    },
    AI_TIMEOUT + 10000,
  );
});
